#!/usr/bin/env node
/**
 * Turn a reviewed corpus report into SQL for profile_facts / profile_fact_variants.
 *
 *   node packages/db/scripts/import-cv-corpus.mjs report.json \
 *     --user <userId> [--merges corpus-review.md] --out import.sql
 *
 * Emits SQL rather than writing to D1 directly, for the same reason the miner
 * emits a report rather than rows: this data ends up in documents sent to
 * employers, so there is a file to read before anything is applied.
 *
 * Merges come from the review sheet's ticked checkboxes. Nothing merges unless a
 * human ticked it.
 *
 * The SQL is idempotent. Facts upsert on their deterministic id; variants rely
 * on the unique index over (user_id, content_hash) and do nothing on conflict.
 * Running it twice changes nothing the second time, which is verified rather
 * than asserted.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const q = (v) =>
  v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;

function parseMerges(path) {
  const merges = [];
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    // Only ticked boxes. "- [x] `keep` <- `merge`"
    const m = line.match(/^\s*-\s*\[[xX]\]\s*`([^`]+)`\s*<-\s*`([^`]+)`/);
    if (m) merges.push({ keep: m[1], drop: m[2] });
  }
  return merges;
}

/** Follow merge chains so B->A and C->B both land on A. */
function resolve(merges) {
  const to = new Map(merges.map((m) => [m.drop, m.keep]));
  const final = new Map();
  for (const drop of to.keys()) {
    const seen = new Set([drop]);
    let cur = to.get(drop);
    while (to.has(cur) && !seen.has(cur)) {
      seen.add(cur);
      cur = to.get(cur);
    }
    final.set(drop, cur);
  }
  return final;
}

const [, , reportPath, ...rest] = process.argv;
const arg = (name) => {
  const i = rest.indexOf(name);
  return i === -1 ? null : rest[i + 1];
};
const userId = arg('--user');
const outPath = arg('--out');
const mergesPath = arg('--merges');

if (!reportPath || !userId || !outPath) {
  console.error(
    'usage: import-cv-corpus.mjs <report.json> --user <userId> --out <file.sql> [--merges <review.md>]',
  );
  process.exit(64);
}

const report = JSON.parse(readFileSync(reportPath, 'utf8'));
const mergeMap = mergesPath ? resolve(parseMerges(mergesPath)) : new Map();

// Fold merged clusters into their survivor, keeping every phrasing.
const facts = new Map();
for (const f of report.facts) {
  const target = mergeMap.get(f.id) ?? f.id;
  const existing = facts.get(target);
  if (!existing) {
    facts.set(target, { ...f, id: target, variants: [...f.variants] });
  } else {
    existing.variants.push(...f.variants);
    existing.uses += f.uses;
  }
}

// One role fact per employer, with its bullets hanging off it. Employer, title
// and dates live there rather than being repeated on every bullet.
const roles = new Map();
for (const f of facts.values()) {
  if (!f.employer || f.employer === '(unknown)') continue;
  const r = roles.get(f.employer) ?? { titles: new Map(), dates: new Map() };
  if (f.roleTitle) r.titles.set(f.roleTitle, (r.titles.get(f.roleTitle) ?? 0) + f.uses);
  if (f.dates) r.dates.set(f.dates, (r.dates.get(f.dates) ?? 0) + f.uses);
  roles.set(f.employer, r);
}
const commonest = (m) => [...m.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;

const FACT_COLS =
  'id,user_id,kind,parent_fact_id,employer,role_title,location,start_date,end_date,canonical,tags,status,created_at,updated_at';
const VARIANT_COLS =
  'id,fact_id,user_id,content,content_hash,source,source_role_title,source_company,used_at,created_at';

const now = Math.floor(Date.now() / 1000);
const lines = [
  '-- Generated by import-cv-corpus.mjs. Review before applying.',
  `-- user: ${userId}  facts: ${facts.size}  roles: ${roles.size}`,
  `-- merges applied: ${mergeMap.size}`,
  'BEGIN TRANSACTION;',
  '',
];

const seenVariants = new Set();
let sharedVariants = 0;
const roleIdFor = new Map();
for (const [employer, r] of roles) {
  const title = commonest(r.titles);
  const dates = commonest(r.dates);
  // Hash the employer rather than slicing its name: a prefix of the raw bytes
  // collides for anything sharing a leading substring, which silently merged
  // "Foundamental VC" and "Foundamental GmbH" into a single role.
  const id = `pf_role_${createHash('sha1').update(employer).digest('hex').slice(0, 20)}`;
  roleIdFor.set(employer, id);
  lines.push(
    `INSERT INTO profile_facts (${FACT_COLS}) VALUES (${q(id)},${q(userId)},'role',NULL,${q(employer)},${q(title)},NULL,${q(dates)},NULL,${q(`${title ?? 'Role'} at ${employer}`)},NULL,'active',${now},${now}) ON CONFLICT(id) DO UPDATE SET role_title=excluded.role_title, start_date=excluded.start_date, updated_at=${now};`,
  );
}
lines.push('');

for (const f of facts.values()) {
  const parent = f.employer ? (roleIdFor.get(f.employer) ?? null) : null;
  lines.push(
    `INSERT INTO profile_facts (${FACT_COLS}) VALUES (${q(f.id)},${q(userId)},'bullet',${q(parent)},NULL,NULL,NULL,NULL,NULL,${q(f.canonical)},NULL,'active',${now},${now}) ON CONFLICT(id) DO UPDATE SET canonical=excluded.canonical, parent_fact_id=excluded.parent_fact_id, updated_at=${now};`,
  );
  for (const v of f.variants) {
    // Deduped across every fact, not just within one. The unique index is over
    // (user_id, content_hash), so a phrasing appearing under two facts is stored
    // once regardless; emitting it twice only makes the reported count disagree
    // with what actually lands in the database.
    if (seenVariants.has(v.contentHash)) {
      sharedVariants++;
      continue;
    }
    seenVariants.add(v.contentHash);
    const vid = `pv_${v.contentHash.slice(0, 24)}`;
    lines.push(
      `INSERT INTO profile_fact_variants (${VARIANT_COLS}) VALUES (${q(vid)},${q(f.id)},${q(userId)},${q(v.content)},${q(v.contentHash)},${q(v.source)},${q(v.sourceRoleTitle)},${q(v.sourceCompany)},NULL,${now}) ON CONFLICT(user_id,content_hash) DO NOTHING;`,
    );
  }
}

lines.push('', 'COMMIT;', '');
writeFileSync(outPath, lines.join('\n'));

console.log(`merges applied:  ${mergeMap.size}`);
console.log(`role facts:      ${roles.size}`);
console.log(`bullet facts:    ${facts.size}`);
console.log(`variants:        ${seenVariants.size}`);
if (sharedVariants) {
  console.log(
    `  (${sharedVariants} duplicate phrasing(s) collapsed - the same wording reused across CVs)`,
  );
}
console.log(`sql written:     ${outPath}`);
